test('get_msg uses account-local playable video metadata even when QQ omits or contradicts optional fields', async t => {
    const { root, directory } = fixture(t), keyFile = path.join(root, 'key');
    fs.writeFileSync(keyFile, '57'.repeat(32), { mode: 0o600 });
    const real = media.exportMedia(directory, 'video', h264), other = media.exportMedia(directory, 'video', webm);
    const store = new MessageStore({ directory: path.join(root, 'messages') });
    try {
    const state = { ready: true, epoch: 'epoch', self: { uin: '123', uid: 'u_123' }, capabilities: { videoReceive: true } };
    let resource = real;
    const backend = { async call(method, params) {
        if (method === 'status') return state;
        assert.equal(method, 'receiveMedia'); assert.equal(params.expectedEpoch, 'epoch');
        assert.deepEqual(params.peer, { chatType: 2, peerUid: '200' });
        // Stale bridge metadata cannot replace the actual per-account bytes.
        return { ...resource, width: 999, height: 998, duration: 777 };
    } };
    const service = new OneBotService({ backend, store, mediaDirectory: directory, mediaBaseUrl: 'https://panel.test/media/first',
        mediaSigningKeyFile: keyFile, profileId: 'first' });
    let sequence = 0;
    const query = async (optional = {}) => {
        const record = { chatType: 2, peerUid: '200', senderUin: '456', senderUid: 'u_456', msgId: String(900 + sequence++), msgTime: '1000',
            elements: [{ elementType: 5, elementId: 'element', videoElement: { fileName: 'movie.mp4', ...optional } }] };
        const entry = store.remember('123', record);
        return service.action({ action: 'get_msg', params: { message_id: entry.id } });
    };
    for (const optional of [{}, { fileWidth: 1, fileHeight: 2, fileTime: 3 }]) {
        const result = await query(optional); assert.equal(result.status, 'ok'); assert.equal(result.retcode, 0);
        const segment = result.data.message[0]; assert.equal(segment.type, 'video');
        assert.equal(segment.data.width, 320); assert.equal(segment.data.height, 180); assert.equal(segment.data.duration, 2);
        assert.equal(segment.data.file_size, String(h264.length)); assert.match(segment.data.url, /signature=/);
        assert.equal('path' in segment.data, false);
    }
    resource = other;
    const fallback = await query(); assert.equal(fallback.status, 'ok');
    for (const field of ['width', 'height', 'duration']) assert.equal(Object.hasOwn(fallback.data.message[0].data, field), false);
    const native = await query({ fileWidth: 640, fileHeight: 480, fileTime: 2.5 });
    assert.equal(native.data.message[0].data.width, 640); assert.equal(native.data.message[0].data.height, 480);
    assert.equal(native.data.message[0].data.duration, 2.5);
    const foreign = path.join(root, 'other-account'); fs.mkdirSync(foreign, { mode: 0o700 });
    resource = media.exportMedia(foreign, 'video', h264);
    assert.notEqual((await query()).retcode, 0);
    } finally { store.close(); }
});

test('resource conversion retains reliable metadata and falls back only to valid native optional values', async () => {
    const element = { elementType: 5, videoElement: { fileWidth: 640, fileHeight: 480, fileTime: 9 } };
    const result = await codec.fromKernel({ elements: [element] }, { video: async () => ({ file: 'id', url: 'https://panel.test/video',
        width: 320, height: 180, duration: 2 }) });
    assert.equal(result[0].data.width, 320); assert.equal(result[0].data.height, 180); assert.equal(result[0].data.duration, 2);
    for (const value of ['320', -1, Infinity, NaN, 9007199254740992]) {
        const fallback = await codec.fromKernel({ elements: [element] }, { video: async () => ({ file: 'id', url: 'https://panel.test/video', width: value, height: value, duration: value }) });
        assert.equal(fallback[0].data.width, 640); assert.equal(fallback[0].data.height, 480); assert.equal(fallback[0].data.duration, 9);
        const absent = await codec.fromKernel({ elements: [{ elementType: 5, videoElement: {} }] }, {
            video: async () => ({ file: 'id', url: 'https://panel.test/video', width: value, height: value, duration: value }) });
        for (const field of ['width', 'height', 'duration']) assert.equal(Object.hasOwn(absent[0].data, field), false);
    }
});

